/**
 * Pixel-art icon bitmaps. '#' = filled pixel, anything else = empty.
 * Every icon is 8×8 so it renders crisp at integer scales.
 */

type Grid = string[];

export function rotateGrid(grid: Grid, turns = 1): Grid {
  let g = grid;
  for (let t = 0; t < ((turns % 4) + 4) % 4; t++) {
    const h = g.length;
    const w = g[0].length;
    g = Array.from({ length: w }, (_, y) =>
      Array.from({ length: h }, (_, x) => g[h - 1 - x][y]).join(""),
    );
  }
  return g;
}

/** Merges each row's filled runs into rects: [x, y, width]. */
export function gridToRuns(grid: Grid): [number, number, number][] {
  const runs: [number, number, number][] = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === "#") end++;
      runs.push([x, y, end - x]);
      x = end;
    }
  });
  return runs;
}

